def shead(eyebrow, title, lede="", center=False, right=""):
    """Section heading. Wrap the muted part of the title in <i>…</i>."""
    lp = f'\n      <p class="lede rise">{lede}</p>' if lede else ""
    cls = "shead center" if center else "shead"
    return f"""<div class="{cls}">
      <div>
        <div class="eyebrow">{eyebrow}</div>
        <h2 class="h2 rise">{title}</h2>{lp}
      </div>{right}
    </div>"""


def faq_block(items, heading="Common <i>questions.</i>"):
    if not items:
        return ""
    qs = "\n".join(f"""      <div class="q" data-open="false">
        <button class="q-btn" aria-expanded="false">{q}<span class="q-ic"></span></button>
        <div class="q-body"><p>{a}</p></div>
      </div>""" for q, a in items)
    return f"""
<section style="padding-top:0">
  <div class="wrap">
    {shead("Questions", heading, center=True)}
    <div class="faqw">
{qs}
    </div>
  </div>
</section>"""


