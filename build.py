def fit_title(*cands, limit=66):
    for c in cands:
        if len(seo.plain(c)) <= limit:
            return c
    return cands[-1]


def fit_desc(text, limit=158):
    t = seo.plain(text)
    if len(t) <= limit:
        return t if len(t) >= 115 else (t + " Call +91 79958 95858.").strip()
    for cut in (" Call +91 79958 95858.", " at Mana Hospitals"):
        if cut in t and len(t.replace(cut, "")) <= limit:
            return t.replace(cut, "")
    t = t[:limit - 1]
    return t[:t.rfind(" ")].rstrip(" ,—-") + "…"


